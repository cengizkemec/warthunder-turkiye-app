'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(__dirname, 'keymap-source.json');
const targetPath = path.join(root, 'src', 'shared', 'keymap.js');

const entries = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

if (!Array.isArray(entries) || entries.length === 0) {
  throw new Error(`No key bindings found in ${sourcePath}`);
}

const seen = new Set();
const unique = entries.filter((entry) => {
  if (!entry || typeof entry.code !== 'string' || seen.has(entry.code)) return false;
  seen.add(entry.code);
  return typeof entry.vk === 'number';
});

const lines = unique
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.code)}: { vk: ${entry.vk}, key: ${JSON.stringify(
        String(entry.key ?? '')
      )}, label: ${JSON.stringify(String(entry.label ?? entry.code))} },`
  )
  .join('\n');

const output = `'use strict';

// Generated by scripts/gen-keymap.js. Source: scripts/keymap-source.json.
const KEYMAP = Object.freeze({
${lines}
});

const ALIASES = Object.freeze({
  alt: 'AltLeft',
  shift: 'ShiftLeft',
  ctrl: 'ControlLeft',
  capslock: 'CapsLock',
  space: 'Space',
  tab: 'Tab',
  enter: 'Enter',
  escape: 'Escape',
  backspace: 'Backspace',
});

function normalizeKey(value) {
  if (typeof value !== 'string' || !value) return 'AltLeft';
  if (KEYMAP[value]) return value;

  const lower = value.toLowerCase();
  if (ALIASES[lower]) return ALIASES[lower];

  if (/^[a-z]$/.test(lower)) {
    const code = 'Key' + lower.toUpperCase();
    if (KEYMAP[code]) return code;
  }

  if (/^[0-9]$/.test(lower)) {
    const code = 'Digit' + lower;
    if (KEYMAP[code]) return code;
  }

  if (/^f([1-9]|1[0-9]|2[0-4])$/.test(lower)) {
    const code = lower.toUpperCase();
    if (KEYMAP[code]) return code;
  }

  return 'AltLeft';
}

function tryBindingFor(value) {
  if (typeof value !== 'string' || !value) return null;

  let code = null;

  if (KEYMAP[value]) {
    code = value;
  } else {
    const lower = value.toLowerCase();

    if (ALIASES[lower]) {
      code = ALIASES[lower];
    } else if (/^[a-z]$/.test(lower)) {
      const candidate = 'Key' + lower.toUpperCase();
      if (KEYMAP[candidate]) code = candidate;
    } else if (/^[0-9]$/.test(lower)) {
      const candidate = 'Digit' + lower;
      if (KEYMAP[candidate]) code = candidate;
    } else if (/^f([1-9]|1[0-9]|2[0-4])$/.test(lower)) {
      const candidate = lower.toUpperCase();
      if (KEYMAP[candidate]) code = candidate;
    }
  }

  if (!code) return null;

  const binding = KEYMAP[code];

  return {
    code,
    vk: binding.vk,
    key: binding.key,
    label: binding.label,
  };
}

function bindingFor(value) {
  return tryBindingFor(value) || tryBindingFor('AltLeft');
}

module.exports = { KEYMAP, ALIASES, normalizeKey, tryBindingFor, bindingFor };
`;

fs.writeFileSync(targetPath, output, 'utf8');
console.log(`Wrote ${unique.length} bindings to ${targetPath}`);
